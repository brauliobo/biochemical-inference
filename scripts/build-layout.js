#!/usr/bin/env node
// Build and check the hand-laid metabolic maps in src/viz/layouts/*.js.
//
//   node scripts/build-layout.js              rewrite the generated block of every layout, then check
//   node scripts/build-layout.js --check      check only; fail when a generated block is stale
//   node scripts/build-layout.js core-methylation gastric-acid     limit to named layouts
//   node scripts/build-layout.js --json       machine readable report
//
// A layout file holds hand-laid coordinates (nodes, groups, links) and a generated block (edges and reaction
// details) derived from the reaction entities of the knowledge base. The script
//   - requires every node id to exist, with a kind equal to the entity type, and numeric coordinates;
//   - requires every reaction that is a member of the layout's pathways to be placed;
//   - requires every participant of a placed reaction to be placed, or to be a pooled currency metabolite
//     (the shared CURRENCY_IDS list plus the layout's own `pool`);
//   - requires every quantity named in `quantRefs` (node id -> quant ids, for flux encoding) to exist;
//   - refuses overlapping nodes and nodes outside the view box;
//   - rewrites the generated block (edges: substrate/product arrows between placed nodes; reactions: enzymes,
//     reversibility and the pooled currency metabolites of each reaction).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { buildGraph } from '../src/knowledge/graph.js'
import { findOverlaps, outOfBounds } from '../src/viz/layouts/geometry.js'

const ROOT = resolve(import.meta.dirname, '..')
export const LAYOUT_DIR = join(ROOT, 'src/viz/layouts')
const NOT_LAYOUTS = new Set(['geometry.js', 'index.js'])

/**
 * Small, ubiquitous metabolites drawn as pooled labels on a reaction instead of as nodes of their own,
 * unless a layout places them explicitly (the gastric map does for H+, CO2, HCO3- and Cl-).
 */
export const CURRENCY_IDS = new Set([
  'compound:water', 'compound:proton', 'compound:phosphate', 'compound:pyrophosphate', 'compound:oxygen', 'compound:hydrogen-peroxide',
  'compound:atp', 'compound:adp', 'compound:amp', 'compound:ctp', 'compound:cmp', 'compound:coa', 'compound:acetyl-coa',
  'compound:nad', 'compound:nadh', 'compound:nadp', 'compound:nadph',
  'compound:carbon-dioxide', 'compound:ammonia', 'compound:chloride',
  'compound:etf-oxidized', 'compound:etf-reduced', 'compound:hydrogen-acceptor', 'compound:hydrogen-acceptor-reduced',
  'compound:thioredoxin-dithiol', 'compound:thioredoxin-disulfide', 'compound:2-oxoglutarate', 'compound:glutamate', 'compound:succinate'
])

const BEGIN = '// BEGIN GENERATED by scripts/build-layout.js'
const END = '// END GENERATED'
const GENERATED_PATTERN = new RegExp(`${BEGIN}[^\\n]*\\n[\\s\\S]*?\\n${END}`)

const q = (text) => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const part = (item) => `{ id: ${q(item.id)}, n: ${item.n} }`

function participants(reaction) {
  const read = (list) => (list ?? []).map((item) => ({ id: typeof item === 'string' ? item : item.id, n: item.n ?? 1 }))
  return { substrates: read(reaction.reaction.reactants), products: read(reaction.reaction.products), enzymes: reaction.reaction.enzymes ?? [] }
}

/** Entities indexed by id. */
export const indexEntities = (entities) => new Map(entities.map((entity) => [entity.id, entity]))

/** Reaction ids that belong to any of the given pathways (reaction part-of pathway), in graph order. */
export function pathwayReactions(graph, pathways) {
  const found = new Set()
  for (const pathway of pathways) {
    for (const edge of graph.incoming(pathway)) if (edge.rel === 'part-of' && graph.get(edge.from)?.type === 'reaction') found.add(edge.from)
  }
  return [...found]
}

/** { edges, reactions } derived from the placed reactions; participants neither placed nor pooled are reported in `issues`. */
export function deriveLayout(layout, byId) {
  const placed = new Set(layout.nodes.map((node) => node.id))
  const pool = new Set(layout.pool ?? [])
  const edges = []
  const reactions = {}
  const issues = []
  for (const node of layout.nodes.filter((item) => item.kind === 'reaction')) {
    const entity = byId.get(node.id)
    if (!entity?.reaction) continue
    const { substrates, products, enzymes } = participants(entity)
    const pooled = { substrates: [], products: [] }
    const drawn = { substrates: [], products: [] }
    for (const [side, list, role] of [['substrates', substrates, 'substrate'], ['products', products, 'product']]) {
      for (const item of list) {
        if (placed.has(item.id)) {
          drawn[side].push(item)
          edges.push(role === 'substrate' ? { from: item.id, to: node.id, role, n: item.n } : { from: node.id, to: item.id, role, n: item.n })
        } else if (CURRENCY_IDS.has(item.id) || pool.has(item.id)) pooled[side].push(item)
        else issues.push({ rule: 'participant-missing', id: node.id, message: `${role} ${item.id} has no node and is neither a currency metabolite nor in the layout's pool` })
      }
    }
    reactions[node.id] = { enzymes, reversible: entity.reaction.reversible === true, substrates: drawn.substrates, products: drawn.products, pooled }
  }
  return { edges, reactions, issues }
}

/** Structural and ontology checks of one layout. Returns [{ rule, id, message }]. */
export function checkLayout(layout, entities, quant = []) {
  const quantIds = new Set(quant.map((record) => record.id))
  const byId = indexEntities(entities)
  const graph = buildGraph(entities)
  const issues = []
  const add = (rule, id, message) => issues.push({ rule, id, message })
  const ids = new Set()
  const groups = new Set((layout.groups ?? []).map((group) => group.id))

  if (!layout.viewBox || !(layout.viewBox.width > 0) || !(layout.viewBox.height > 0)) add('view-box', layout.id, 'viewBox needs a positive width and height')
  for (const node of layout.nodes) {
    if (ids.has(node.id)) add('duplicate-node', node.id, 'node placed twice')
    ids.add(node.id)
    const entity = byId.get(node.id)
    if (!entity) add('unknown-entity', node.id, 'no such entity in the knowledge base')
    else if (entity.type !== node.kind) add('kind-mismatch', node.id, `kind '${node.kind}' but the entity is a ${entity.type}`)
    if (!Number.isFinite(node.x) || !Number.isFinite(node.y)) add('coordinates', node.id, 'x and y must be finite numbers')
    if (typeof node.label !== 'string' || !node.label.trim()) add('label', node.id, 'node needs a label')
    if (node.group !== undefined && !groups.has(node.group)) add('unknown-group', node.id, `group '${node.group}' is not declared`)
  }
  for (const id of layout.pool ?? []) {
    if (!byId.has(id)) add('unknown-entity', id, 'pool entry is not an entity')
    if (ids.has(id)) add('pool-and-node', id, 'a pooled metabolite must not also be a node')
  }
  for (const [nodeId, refs] of Object.entries(layout.quantRefs ?? {})) {
    if (!ids.has(nodeId)) add('quant-ref-node', nodeId, 'quantRefs names a node that is not placed')
    for (const ref of refs) if (!quantIds.has(ref)) add('quant-ref', nodeId, `quantity ${ref} does not exist`)
  }
  for (const link of layout.links ?? []) {
    for (const end of [link.from, link.to]) if (!ids.has(end)) add('unknown-link-end', `${link.from}->${link.to}`, `${end} has no node`)
  }
  const placedReactions = new Set(layout.nodes.filter((node) => node.kind === 'reaction').map((node) => node.id))
  for (const id of [...pathwayReactions(graph, layout.pathways ?? []), ...(layout.extraReactions ?? [])]) {
    if (!placedReactions.has(id)) add('reaction-missing', id, `member reaction of ${(layout.pathways ?? []).join(', ')} has no coordinates`)
  }
  for (const pathway of layout.pathways ?? []) if (byId.get(pathway)?.type !== 'pathway') add('unknown-pathway', pathway, 'layout.pathways entry is not a pathway')
  if (layout.nodes.every((node) => Number.isFinite(node.x) && Number.isFinite(node.y))) {
    for (const [a, b] of findOverlaps(layout.nodes)) add('overlap', `${a} / ${b}`, 'node footprints overlap')
    if (layout.viewBox) for (const id of outOfBounds(layout.nodes, layout.viewBox)) add('out-of-bounds', id, 'node leaves the view box')
  }
  issues.push(...deriveLayout(layout, byId).issues)
  return issues
}

/** Source text of the generated block for a derivation. */
export function renderGenerated({ edges, reactions }) {
  const lines = [`${BEGIN} (edges and reaction details derived from the ontology reactions; do not edit by hand)`, 'const generated = {', '  edges: [']
  edges.forEach((edge, index) => lines.push(`    { from: ${q(edge.from)}, to: ${q(edge.to)}, role: ${q(edge.role)}, n: ${edge.n} }${index < edges.length - 1 ? ',' : ''}`))
  lines.push('  ],', '  reactions: {')
  const keys = Object.keys(reactions)
  keys.forEach((key, index) => {
    const item = reactions[key]
    const list = (items) => `[${items.map(part).join(', ')}]`
    lines.push(`    ${q(key)}: {`)
    lines.push(`      enzymes: [${item.enzymes.map(q).join(', ')}],`)
    lines.push(`      reversible: ${item.reversible},`)
    lines.push(`      substrates: ${list(item.substrates)},`)
    lines.push(`      products: ${list(item.products)},`)
    lines.push(`      pooled: { substrates: ${list(item.pooled.substrates)}, products: ${list(item.pooled.products)} }`)
    lines.push(`    }${index < keys.length - 1 ? ',' : ''}`)
  })
  lines.push('  }', '}', END)
  return lines.join('\n')
}

export function replaceGenerated(source, derivation) {
  if (!GENERATED_PATTERN.test(source)) throw new Error(`generated block markers not found (${BEGIN} ... ${END})`)
  return source.replace(GENERATED_PATTERN, () => renderGenerated(derivation))
}

export function layoutNames() {
  return readdirSync(LAYOUT_DIR).filter((name) => name.endsWith('.js') && !NOT_LAYOUTS.has(name)).map((name) => name.replace(/\.js$/, '')).sort()
}

export async function loadLayout(name) {
  return (await import(`${pathToFileURL(join(LAYOUT_DIR, `${name}.js`)).href}?t=${Date.now()}`)).default
}

async function main() {
  const args = process.argv.slice(2)
  const json = args.includes('--json')
  const checkOnly = args.includes('--check')
  const named = args.filter((arg) => !arg.startsWith('--'))
  const entities = (await import(pathToFileURL(join(ROOT, 'src/knowledge/data/index.js')).href)).default
  const quant = (await import(pathToFileURL(join(ROOT, 'src/knowledge/data/quant.js')).href)).default
  const byId = indexEntities(entities)
  const report = []
  let failed = false
  for (const name of named.length ? named : layoutNames()) {
    const file = join(LAYOUT_DIR, `${name}.js`)
    let layout = await loadLayout(name)
    const derivation = deriveLayout(layout, byId)
    if (!checkOnly) {
      const source = readFileSync(file, 'utf8')
      const next = replaceGenerated(source, derivation)
      if (next !== source) {
        writeFileSync(file, next)
        layout = await loadLayout(name)
      }
    }
    const issues = checkLayout(layout, entities, quant)
    const current = deriveLayout(layout, byId)
    const fresh = JSON.stringify(layout.edges) === JSON.stringify(current.edges) && JSON.stringify(layout.reactions) === JSON.stringify(current.reactions)
    if (!fresh) issues.push({ rule: 'stale-generated', id: name, message: 'generated block is out of date; run node scripts/build-layout.js' })
    const kinds = Object.fromEntries(Object.entries(Object.groupBy(layout.nodes, (node) => node.kind)).map(([kind, list]) => [kind, list.length]))
    report.push({ name, nodes: layout.nodes.length, kinds, edges: layout.edges.length, links: (layout.links ?? []).length, issues })
    if (issues.length) failed = true
  }
  if (json) process.stdout.write(`${JSON.stringify({ ok: !failed, layouts: report }, null, 2)}\n`)
  else {
    for (const item of report) {
      const kinds = Object.entries(item.kinds).map(([kind, count]) => `${kind} ${count}`).join(', ')
      process.stdout.write(`${item.issues.length ? 'FAIL' : 'ok  '} ${item.name}: ${item.nodes} nodes (${kinds}), ${item.edges} edges, ${item.links} links\n`)
      for (const issue of item.issues) process.stdout.write(`       ${issue.rule}: ${issue.id}: ${issue.message}\n`)
    }
    process.stdout.write(failed ? 'Layouts: FAILED\n' : 'Layouts: OK\n')
  }
  process.exitCode = failed ? 1 : 0
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) await main()
