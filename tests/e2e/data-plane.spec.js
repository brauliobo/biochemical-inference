import { expect, test } from '@playwright/test'

test('syncs the signed release pair, audits it offline, and traverses local pages on desktop and mobile', async ({ page }) => {
  await page.goto('/#/workbench/full')
  const panel = page.getByRole('region', { name: 'Data plane workbench' })
  await expect(panel.getByRole('heading', { name: 'Data plane workbench' })).toBeVisible()
  await expect(panel.getByText('Local / offline reads')).toBeVisible()
  const sync = panel.getByRole('button', { name: /Sync release pair|Re-verify release pair/ })
  await expect(sync).toBeEnabled()
  await sync.click()

  await expect(panel.getByText('one-carbon-authority-human-mouse-v2.0.0').first()).toBeVisible({ timeout: 30_000 })
  await expect(panel.getByText('one-carbon-authority-human-mouse-v2.0.1').first()).toBeVisible()
  await expect(panel.getByText('310bd8a04320c9b1bd9d4e18795bd998627265ac11b1c0e2b07a0473ba48f8e0').first()).toBeVisible()
  await expect(panel.getByText('9dad9f1ac92ff2c53810867414c7729a1ee97425213b9749482ebe2fd37874b5').first()).toBeVisible()
  await expect(panel.getByText('goal11-release-2026 · retired').first()).toBeVisible()
  await expect(panel.getByText('goal11-release-2026-rotation-1 · active').first()).toBeVisible()
  await expect(panel.getByText('yWbisY7eaKIvpoUkoLb28XGGpimerBSmmsAutm9kSvM')).toBeVisible()
  await expect(panel.getByText('IQyu5Evu5OzUFJXuUU5qq27H7pwiUfLHKKi6YQn0reE')).toBeVisible()
  await expect(panel.getByText('Authority response')).toHaveCount(9)
  await expect(panel.getByText('Repository curation')).toHaveCount(2)
  await expect(panel.getByText('Courtesy of the U.S. National Library of Medicine.', { exact: true })).toBeVisible()
  await expect(panel.getByText(/SHMT1 · Serine hydroxymethyltransferase/)).toBeVisible()
  await expect(panel.getByText(/Shmt1 · Serine hydroxymethyltransferase/)).toBeVisible()
  await expect(panel.getByText('CHEBI:15377', { exact: true })).toBeVisible()

  const pagination = panel.getByRole('navigation', { name: 'Record pagination' })
  await pagination.getByRole('button', { name: 'Next' }).click()
  await expect(panel.getByText('CHEBI:33384', { exact: true })).toBeVisible()
  await pagination.getByRole('button', { name: 'Next' }).click()
  await expect(panel.getByText('CHEBI:57453', { exact: true })).toBeVisible()
  await expect(pagination.getByText('Page 3')).toBeVisible()
  await expect(panel.getByText('1 changes')).toBeVisible()
  await expect(panel.getByText(/16 records are unchanged/)).toBeVisible()
  await expect(panel.getByText(/adapter:pubmed-esummary-json-doi@1.1.0/)).toBeVisible()

  const audit = panel.getByRole('button', { name: /Run offline audit|Re-run idempotent audit/ })
  await audit.click()
  await expect(panel.getByText('authority-closure-audit-v1.0.0')).toBeVisible()
  await expect(panel.getByText('17 records · 10 partitions')).toBeVisible()
  await expect(panel.getByText('unsupported', { exact: true })).toBeVisible()

  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  expect(overflow).toBeLessThanOrEqual(1)
})
